"""Generate synthetic inflammatory trajectories for a competition/research PoC.

These trajectories are generated by a simplified biological ODE for a
competition/research proof-of-concept. They are not clinical measurements and
must not be used for diagnosis, treatment, or medical decision-making.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

from src.biotwin.models.biological_ode import BiologicalParameters, simulate_trajectory


def _build_patient_stimulus(rng: np.random.Generator, n_hours: int) -> np.ndarray:
    """Create a non-negative inflammatory stimulus with baseline, pulse, and recovery."""
    time = np.arange(n_hours, dtype=float)
    baseline = rng.uniform(0.05, 0.35)
    max_pulse_duration = max(4, min(n_hours // 2, 36))
    pulse_duration = int(rng.integers(4, max_pulse_duration + 1))
    pulse_start = int(rng.integers(0, max(1, n_hours - pulse_duration + 1)))
    pulse_peak = rng.uniform(1.2, 4.5)

    rise_steps = max(2, pulse_duration // 2)
    fall_steps = max(1, pulse_duration - rise_steps)
    pulse_rise = np.linspace(0.0, pulse_peak, rise_steps + 1, endpoint=True)
    pulse_fall = np.linspace(pulse_peak, 0.0, fall_steps, endpoint=False)
    pulse_profile = np.concatenate([pulse_rise[:-1], pulse_fall])
    pulse_profile = pulse_profile[:pulse_duration]

    pulse_array = np.zeros(n_hours)
    pulse_end = min(n_hours, pulse_start + pulse_duration)
    pulse_array[pulse_start:pulse_end] = pulse_profile[: pulse_end - pulse_start]

    sustained = 0.1 * np.sin(2.0 * np.pi * time / 24.0) + 0.05 * np.sin(2.0 * np.pi * time / 7.0)
    stimulus = baseline + sustained + pulse_array
    return np.maximum(0.0, stimulus)


def generate_inflammatory_trajectories(
    n_patients: int = 100,
    n_hours: int = 168,
    seed: int = 42,
) -> pd.DataFrame:
    """Generate a deterministic synthetic inflammatory trajectory dataset."""
    if isinstance(n_patients, bool) or not isinstance(n_patients, (int, np.integer)):
        raise ValueError("n_patients must be a positive integer")
    if n_patients <= 0:
        raise ValueError("n_patients must be a positive integer")
    if isinstance(n_hours, bool) or not isinstance(n_hours, (int, np.integer)):
        raise ValueError("n_hours must be a positive integer")
    if n_hours <= 0:
        raise ValueError("n_hours must be a positive integer")

    rng = np.random.default_rng(seed)
    patient_ids = [f"P{index:06d}" for index in range(1, int(n_patients) + 1)]
    rows: list[dict[str, float | str]] = []

    for patient_index, patient_id in enumerate(patient_ids):
        initial_il6 = float(rng.uniform(0.05, 1.2))
        initial_crp = float(rng.uniform(0.05, 1.5))
        stimulus = _build_patient_stimulus(rng, int(n_hours))
        alpha_il6 = float(rng.uniform(0.8, 2.5))
        k_il6 = float(rng.uniform(0.12, 0.45))
        alpha_crp = float(rng.uniform(0.4, 1.8))
        k_crp = float(rng.uniform(0.05, 0.25))
        params = BiologicalParameters(
            alpha_il6=alpha_il6,
            k_il6=k_il6,
            alpha_crp=alpha_crp,
            k_crp=k_crp,
        )

        trajectory = simulate_trajectory(
            initial_il6=initial_il6,
            initial_crp=initial_crp,
            stimulus=stimulus,
            dt=1.0,
            params=params,
        )
        trajectory = trajectory.assign(patient_id=patient_id)
        trajectory["time_hours"] = trajectory["time"]
        trajectory["patient_id"] = patient_id
        trajectory = trajectory[["patient_id", "time_hours", "stimulus", "il6", "crp"]]
        rows.extend(trajectory.to_dict(orient="records"))

    output = pd.DataFrame(rows)
    output = output[["patient_id", "time_hours", "stimulus", "il6", "crp"]]
    return output


if __name__ == "__main__":
    output_path = Path("data/synthetic/synthetic_inflammatory_trajectories.csv")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    trajectories = generate_inflammatory_trajectories(n_patients=100, n_hours=168, seed=42)
    trajectories.to_csv(output_path, index=False)
    print("Synthetic inflammatory trajectories generated successfully.")
    print(f"Patients: {trajectories['patient_id'].nunique()}")
    print(f"Hours: {trajectories['time_hours'].nunique().max() if not trajectories.empty else 0}")
    print(f"Rows: {len(trajectories)}")
    print(f"Output: {output_path.as_posix()}")
